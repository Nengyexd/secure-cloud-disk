-- =============================================
-- 基于AES加密的安全云盘系统 - 数据库更新/迁移脚本
-- =============================================
-- 说明：此脚本用于在已有数据库基础上进行结构升级
-- 执行方式：直接在 MySQL 中运行本脚本
-- 注意：执行前请备份数据库
-- =============================================

USE secure_cloud_disk;

-- =============================================
-- 版本 1.1 - 2026-01-05
-- 功能：文件列表和管理模块
-- =============================================

-- 1. 允许文件夹的 encrypted_key 和 storage_key 为空
ALTER TABLE `files`
MODIFY COLUMN `encrypted_key` VARCHAR(512) NULL COMMENT '加密后的文件密钥（文件夹可为空）',
MODIFY COLUMN `storage_key` VARCHAR(255) NULL COMMENT 'MinIO存储键（文件夹可为空）';

-- 2. 扩大 file_type 字段长度
ALTER TABLE `files`
MODIFY COLUMN `file_type` VARCHAR(100) NULL COMMENT '文件MIME类型';

-- =============================================
-- 版本 1.2 - 2026-01-07
-- 功能：用户头像功能
-- =============================================

-- 3. 添加用户头像字段
ALTER TABLE `users`
ADD COLUMN `avatar` VARCHAR(255) NULL COMMENT '用户头像URL' AFTER `email_verified`;

-- =============================================
-- 版本 1.3 - 2026-01-08
-- 功能：图片缩略图支持
-- =============================================

-- 4. 添加缩略图字段
ALTER TABLE `files`
ADD COLUMN `thumbnail_key` VARCHAR(255) NULL COMMENT '缩略图存储键（仅图片文件）' AFTER `storage_key`;

-- =============================================
-- 验证更新是否成功
-- =============================================
-- 执行以下查询验证表结构是否正确更新：

-- 查看 files 表结构
-- DESC files;

-- 查看 users 表结构
-- DESC users;

-- =============================================
-- 注意事项
-- =============================================
-- 1. 此脚本只修改表结构，不会删除或修改现有数据
-- 2. ALTER TABLE 操作是安全的，MySQL 会保留所有现有数据
-- 3. 如果某个 ALTER TABLE 已经执行过，重复执行可能会报错
-- 4. 建议在执行前备份数据库：
--    mysqldump -u root -p secure_cloud_disk > backup_YYYYMMDD.sql

-- =============================================
-- 完成提示
-- =============================================
SELECT '数据库更新完成！' AS status;
